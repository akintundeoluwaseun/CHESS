#!/usr/bin/env node
/**
 * Embeds the Stockfish 19 "lite single-threaded" WASM engine (from the
 * `stockfish` npm package, GPLv3) into a TypeScript module so the app can run
 * it fully offline inside a WebView worker — no native compilation needed.
 */
const fs = require('fs');
const path = require('path');

const bin = path.join(__dirname, '..', 'node_modules', 'stockfish', 'bin');
const js = fs.readFileSync(path.join(bin, 'stockfish-19-lite-single.js'), 'utf8');
const wasm = fs.readFileSync(path.join(bin, 'stockfish-19-lite-single.wasm')).toString('base64');
const outDir = path.join(__dirname, '..', 'src', 'engine', 'generated');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'stockfishBundle.ts'),
  '/* eslint-disable */\n// AUTO-GENERATED by scripts/build-engine-assets.js — Stockfish 19 lite (GPLv3).\n' +
    `export const SF_JS: string = ${JSON.stringify(js)};\n` +
    `export const SF_WASM_B64: string = ${JSON.stringify(wasm)};\n`,
);
console.log(`Engine bundled: js ${(js.length / 1024).toFixed(0)} KB, wasm(b64) ${(wasm.length / 1024 / 1024).toFixed(2)} MB`);
